import { useState } from "react";
import { Code, Lesson, PageHeader } from "../../components";

interface User {
  firstName: string;
  lastName: string;
  role: string;
  active: boolean;
}

const USERS: User[] = [
  { firstName: "John", lastName: "Smith", role: "Admin", active: true },
  { firstName: "Anna", lastName: "Kowalski", role: "User", active: true },
  { firstName: "Michael", lastName: "Brown", role: "Manager", active: true },
  { firstName: "Sarah", lastName: "Wilson", role: "User", active: true },
  { firstName: "Peter", lastName: "Novak", role: "User", active: false },
  { firstName: "Lena", lastName: "Fischer", role: "Manager", active: false },
];

function toCsv(users: User[]): string {
  const lines = ["firstName,lastName,role", ...users.map((u) => `${u.firstName},${u.lastName},${u.role}`)];
  return lines.join("\n") + "\n";
}

function toJson(users: User[]): string {
  return JSON.stringify(
    users.map(({ firstName, lastName, role }) => ({ firstName, lastName, role })),
    null,
    2,
  );
}

export default function FileDownload() {
  const [format, setFormat] = useState<"csv" | "json">("csv");
  const [includeInactive, setIncludeInactive] = useState(false);
  const [status, setStatus] = useState("");

  const exportUsers = () => {
    const users = includeInactive ? USERS : USERS.filter((user) => user.active);
    const fileName = `users.${format}`;
    const blob =
      format === "csv" ? new Blob([toCsv(users)], { type: "text/csv" }) : new Blob([toJson(users)], { type: "application/json" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = fileName;
    link.click();
    setTimeout(() => URL.revokeObjectURL(url), 1000);
    setStatus(`Exported ${users.length} users to ${fileName}`);
  };

  return (
    <>
      <PageHeader title="File Download">
        Files made in the browser, served as they are, and generated by the server. Catch each one and check what is inside.
      </PageHeader>

      <Lesson title="Testing downloads">
        <h3>Catch the download</h3>
        <p>
          Start to wait for the <code>download</code> event. Then click. Playwright saves the file in a temporary folder. It deletes the folder when
          the browser context closes.
        </p>
        <Code>{`
const downloadPromise = page.waitForEvent('download');
await page.getByRole('button', { name: 'Export users as CSV' }).click();
const download = await downloadPromise;

expect(download.suggestedFilename()).toBe('users.csv');
`}</Code>
        <h3>Read what is inside</h3>
        <p>A file that downloads can still be wrong. Read it and assert its content.</p>
        <Code>{`
const content = await readFile(await download.path(), 'utf-8');
const users = JSON.parse(content);           // for the JSON export
expect(users).toHaveLength(4);
`}</Code>
        <p>
          To keep a file after the test, for example to attach it to the report, use <code>download.saveAs(testInfo.outputPath(name))</code>.
        </p>
        <h3>Names that you cannot predict</h3>
        <p>The server names the monthly report after the current month. Match a pattern. Do not match one exact name.</p>
        <Code>{`
expect(download.suggestedFilename()).toMatch(/^report-\\d{4}-\\d{2}\\.txt$/);
`}</Code>
        <div className="lesson-callout">
          A slow server delays the <code>download</code> event, not the click. The event waits up to the timeout of the test, so a slow file needs no
          extra code.
        </div>
      </Lesson>

      <div className="test-card">
        <h2>Generated file</h2>
        <p>The browser builds the file when you click the button.</p>
        <div className="form-group">
          <label htmlFor="export-format">Format</label>
          <select id="export-format" value={format} onChange={(event) => setFormat(event.target.value as "csv" | "json")}>
            <option value="csv">CSV</option>
            <option value="json">JSON</option>
          </select>
        </div>
        <label className="checkbox-label">
          <input type="checkbox" checked={includeInactive} onChange={(event) => setIncludeInactive(event.target.checked)} />
          Include inactive users
        </label>
        <div className="button-row">
          <button type="button" onClick={exportUsers}>
            Export users as {format.toUpperCase()}
          </button>
        </div>
        {status && (
          <div className="result" role="status">
            {status}
          </div>
        )}
      </div>

      <div className="test-card">
        <h2>Static file</h2>
        <p>A plain link to a file that the app serves.</p>
        <a href="/downloads/sample-report.txt" download className="button-link">
          Download sample report
        </a>
      </div>

      <div className="test-card">
        <h2>Server report</h2>
        <p>The server builds this report when you ask for it. This takes a moment. The name of the file includes the current month.</p>
        <a href="/api/reports/monthly" className="button-link">
          Download monthly report
        </a>
      </div>
    </>
  );
}
